// 版块 i 使用的主题小节
export function themeBarsForScene(i) {
  const b = (3 * i) % THEME_BARS;
  return [b, (b + 1) % THEME_BARS, (b + 2) % THEME_BARS];
}

// ------------------------------------------------------------
// 取某版块的旋律音符
// 返回：{ bar(0..2), beat, dur, semis, vel }  —— bar 为版块内小节
// opts: { scale, octave, skipLong }
// ------------------------------------------------------------
export function sceneThemeNotes(sceneIndex, opts = {}) {
  const bars = themeBarsForScene(sceneIndex);
  const out = [];
  for (let k = 0; k < 3; k++) {
    const src = bars[k];
    for (const n of THEME) {
      if (n[0] !== src) continue;
      out.push({ bar: k, beat: n[1], dur: n[2], semis: n[3], vel: n[4] });
    }
  }
  return out;
}

// 版块内三小节的力度包络：进(0.8) → 高光(1.0) → 出(0.72)
export function sceneBarGain(bar) {
  return [0.80, 1.00, 0.72][bar] ?? 0.85;
}

